// module_export.hpp — сбор экспорт-интерфейса модуля из его AST-тела.
//
// Экспортируются ВСЕ top-level объявления/определения в не-анонимных областях имён
// (глобальная `::`, именованные `ns::`) — см. SYNTAX.md §6.6. Из анонимной области `_`
// и из локальных (внутри функций/блоков) — НЕ экспортируются.
//
// Фильтр интерфейса при импорте: аргументы оператора `\module(mod, masks)` — список
// glob-масок (`*` — любая последовательность, `?` — один символ, через запятую = OR).
// Пустая строка масок означает «экспортировать всё».

#pragma once

#include "ast/ast_nodes.hpp"
#include "syntax/term_types.h"
#include <string_view>
#include <vector>

namespace trust {

/// Сопоставление glob-маски: '*' — любая (возможно пустая) последовательность символов,
/// '?' — ровно один любой символ, остальные — литеральные. Случай-чувствительно.
[[nodiscard]] bool matchGlob(std::string_view pattern, std::string_view name);

/// Список масок (через запятую, пробелы вокруг имени игнорируются) = OR.
/// Пустая/пробельная строка возвращает true (фильтра нет — подходит всё).
[[nodiscard]] bool matchesAnyMask(std::string_view commaMasks, std::string_view name);

/// Собрать экспортируемые декларации модуля из его AST-тела (топ-левел, не-анонимные
/// области). При пустой masks возвращает ВСЕ экспорты; иначе — только подходящие под маски.
/// Возвращает ИСХОДНЫЕ термы объявлений (term()) для кодового имени/range-диагностики.
[[nodiscard]] std::vector<TermPtr> collectExportedDecls(const std::vector<AstNodePtr>& body, std::string_view masks);

} // namespace trust