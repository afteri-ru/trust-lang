#pragma once

// Глубокий клон AST-дерева: граница «неизменяемая AST → независимое производное дерево».
// Контракт:
//   * Исходное дерево НЕ изменяется. Клон владеет своими узлами: клонируются ВСЕ владеемые
//     слоты узла (обход, контракты, скрытые от обхода аннотации/временные/типовые аргументы) —
//     состав задаётся класс-таблицей `ast/slots/node_slots_x.hpp`, а не перечнем в этом файле.
//   * Невладеющие ссылки (строки `NonOwn*` той же таблицы) ремапятся на узлы клона, если цель
//     входит в клонируемое дерево; ссылки на узлы вне дерева (напр. объявления другого модуля)
//     остаются ссылками на исходное дерево — оно живёт дольше клона и доступно только для чтения.
//   * `term` (синтаксический терм) НЕ копируется по значению: `TermPtr` разделяется, потому
//     что Term неизменяем и нужен для спанов/диагностик.

#include "ast/token_base.hpp"
#include "ast/convert/jump_targets.hpp"

#include <vector>

namespace trust {

/// Клон списка узлов с единой картой соответствий (сохраняет разделяемые поддеревья и
/// корректный ремап невладеющих ссылок между узлами списка). Пустой корень остаётся пустым:
/// индексы клона совпадают с индексами входа.
[[nodiscard]] std::vector<AstNodePtr> cloneTrees(const std::vector<AstNodePtr>& nodes);

} // namespace trust
