#pragma once

// include/ir/hir_verify.hpp
// Структурный верификатор HIR — единственный гейт корректности производного представления
// (контракт J2, см. include/ir/hir/MEMORY.md). Проверяет инварианты, которые обязаны выполняться
// при корректной работе анализа/lowering:
//   1) в понижённой форме нет recovery-узлов (`ErrorExpr`);
//   2) каждая аннотация типа материализована семантикой (`IdentName::resolvedTypeId`);
//   2a) левый операнд `MemberAccess` разрешён как значение (`resolvedDecl`) или тип
//      (`IdentName::resolvedTypeId`);
//   3) у каждого `GotoStmt` внутри функции есть РОВНО одна определяющая `LabelStmt`,
//      имена меток не дублируются (метки создаёт lowering; рассогласование — дефект понижения);
//   3a) именованные `break`/`continue` развёрнуты lowering'ом (нет выживших label-переходов);
//   3b) `SemicolonStmt` оборачивает ровно одно не-`SemicolonStmt` выражение;
//   4) у пользовательской нетипизированной переменной с инициализатором есть выведенный тип
//      (`VarDecl::inferredType` — единственный источник для кодогена в этой ветке);
//   4a) `CallExpr::argCasts` согласован по арности со слотами аргументов (boundArgs/m_args);
//   4b) контролируемая арифметика классифицирована (`Binary::m_overflowCheck`);
//   4c) имена синтетических временных уникальны в пределах функции.
//
// Диагностика синтетических узлов использует `origin` (узел исходной AST), если он задан.
// Это внутренняя проверка компилятора (не пользовательская диагностика): нарушение —
// ICE-политика `reportInternalError`.
//
// Верификатор НЕ строит HIR и не мутирует его; вызывается `Pipeline` между `buildHir` и
// flow-анализами, только на успешном прогоне семантики (частичный AST в LSP даёт законные
// «дыры» и не является ICE).

#include "ir/hir_module.hpp"

#include <optional>
#include <string>

namespace trust {

/// nullopt — нарушений нет; иначе — человекочитаемое описание ПЕРВОГО нарушения.
[[nodiscard]] std::optional<std::string> verifyHir(const HirModule& hir);

} // namespace trust
